"""Copies the catalogue migrations from the 1.x Rust engine (crates/dj-core/src/db.rs)
into Dart, so 2.0 opens existing libraries with the identical schema.
Run: python3 tool/gen_migrations.py   (from dj_assistant_flutter/)"""
import re, pathlib
src = pathlib.Path('../crates/dj-core/src/db.rs').read_text()
body = src[src.index('pub const MIGRATIONS: &[&str] = &['):]
body = body[:body.index('\n];')]
parts = re.findall(r'r#"(.*?)"#', body, re.S)
out = ['// GENERATED by tool/gen_migrations.py from crates/dj-core/src/db.rs. Do not edit.',
       '// The catalogue schema is shared with DJ Assistant 1.x, so libraries carry over.', '',
       '/// Migration N (1-based) brings the database to `PRAGMA user_version = N`.',
       'const List<String> migrations = [']
for p in parts:
    out.append("  r'''" + p.replace("'''", "' ' '") + "''',")
out.append('];')
pathlib.Path('lib/core/migrations.g.dart').write_text('\n'.join(out) + '\n')
print(len(parts), 'migrations')

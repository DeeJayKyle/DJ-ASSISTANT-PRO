#!/usr/bin/env python3
"""Checks licences of shipped dependencies (Rust crates in the desktop app and
production npm packages). Fails on copyleft licences that would impose
obligations on a distributed binary. Writes THIRD_PARTY_LICENSES.md."""
import json, subprocess, sys, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
BLOCKED = re.compile(r"\b(A?GPL|LGPL|SSPL|EUPL|CC-BY-NC|MS-RL)", re.I)

def ok(lic: str) -> bool:
    if not lic:
        return False
    # An OR expression is fine if any alternative is acceptable.
    alts = [a.strip(" ()") for a in re.split(r"\s+OR\s+|/", lic)]
    return any(a and not BLOCKED.search(a) for a in alts)

def rust():
    meta = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
    # Resolve only crates reachable from the shipped app (normal deps).
    pk = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    start = [p["id"] for p in meta["packages"] if p["name"] == "dj-assistant"]
    seen, stack = set(), list(start)
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    return sorted({(pk[i]["name"], pk[i]["version"], pk[i].get("license") or "UNKNOWN") for i in seen if pk[i]["source"]})

def npm():
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json"], cwd=ROOT, capture_output=True, text=True, shell=sys.platform == "win32").stdout
    tree = json.loads(out or "{}")
    res = set()
    def walk(deps):
        for name, d in (deps or {}).items():
            pj = ROOT / "node_modules" / name / "package.json"
            lic = "UNKNOWN"
            if pj.exists():
                l = json.loads(pj.read_text(encoding="utf-8")).get("license", "UNKNOWN")
                lic = l if isinstance(l, str) else l.get("type", "UNKNOWN")
            res.add((name, d.get("version", "?"), lic))
            walk(d.get("dependencies"))
    walk(tree.get("dependencies"))
    return sorted(res)

r, n = rust(), npm()
bad = [x for x in r + n if not ok(x[2])]
lines = ["# Third-party licences", "", "Generated by `scripts/check-licenses.py`. Covers dependencies compiled into the desktop app and production front-end packages.", "",
         f"Rust crates: {len(r)}. npm packages: {len(n)}.", "", "SQLite (bundled via libsqlite3-sys) is in the public domain. The Archivo typeface is licensed under the SIL Open Font License 1.1.", "",
         "| Component | Version | Licence |", "|---|---|---|"]
lines += [f"| {a} | {b} | {c} |" for a, b, c in r + n]
(ROOT / "THIRD_PARTY_LICENSES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
if bad:
    print("Licences needing review:")
    for b in bad:
        print("  ", b)
    sys.exit(1)
print(f"OK: {len(r)} Rust crates and {len(n)} npm packages have permissive licences. Wrote THIRD_PARTY_LICENSES.md")
